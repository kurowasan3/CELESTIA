# グラフ：x = 0.10 cos(10 t)。図の作図仕様（振幅 60px = 0.10 m、1周期 140px = π/5 s）とも照合
import json as _j
spec = _j.loads((ROOT / 'content/problems/MEC/MEC-SHM-201/q-graph.fig.json').read_text())
sine = next(i for i in spec['items'] if i['t'] == 'sine')
assert sine['func'] == 'cos' and sine['cycles'] == 2 and sine['amp'] == 60 and sine['to'][0] - sine['from'][0] == 280
A = sp.Rational(1, 10); T = sp.pi / 5; m = sp.Rational(1, 2)
check('MEC-SHM-201', '1', A, T)
w = 2 * sp.pi / T
check('MEC-SHM-201', '2', w)
t = sp.Symbol('t'); x = A * sp.cos(w * t)
vmax = sp.maximum(sp.diff(x, t), t, sp.Interval(0, T))
check('MEC-SHM-201', '3', vmax)
check('MEC-SHM-201', '4', m * w**2)
check('MEC-SHM-201', '5', sp.diff(x, t, 2).subs(t, sp.pi / 10))
