# PHY-IND-049 検証：棒磁石の磁極が小コイルを通過するときの起電力と損失
import sympy as sp, numpy as np
from scipy.integrate import solve_ivp
s,r,P0,u,R,t=sp.symbols('s r Phi0 u R t',positive=True)
S=sp.symbols('s_',real=True)
Phi=P0/2*(1-S/sp.sqrt(S**2+r**2))
dPhi=sp.diff(Phi,S)
V=sp.simplify(-dPhi*u)            # 下向きに速さ u で通過（ds/dt=-u）→ 誘導起電力の大きさ
print('V(s)=',V)
Vmax=sp.simplify(V.subs(S,0)); print('Vmax=',Vmax)
# (2) ∫V dt = ∫ V ds/u
area=sp.integrate(V/u,(S,-sp.oo,sp.oo)); print('area=',sp.simplify(area))
assert sp.simplify(area-P0)==0
# (4) Joule heat
J=sp.integrate(V**2/R/u,(S,-sp.oo,sp.oo)); J=sp.simplify(J); print('J=',J)
J_meas=3*sp.pi*P0*Vmax/(16*R)
assert sp.simplify(J-J_meas)==0
# integral given in problem
print(sp.integrate(1/(S**2+r**2)**3,(S,-sp.oo,sp.oo)))
# (3) ell from peaks
h,hp,l,V1,V2=sp.symbols('h hp l V1 V2',positive=True)
ell=sp.solve(sp.Eq((V2/V1)**2,(hp-l)/(h-l)),l)[0]; print('ell=',sp.factor(ell))
# numeric check with Vpeaks generated by ell
vals={h:0.5,hp:0.4,l:0.2}
V1n=sp.sqrt(2*9.8*(0.5-0.2)); V2n=sp.sqrt(2*9.8*(0.4-0.2))
print('ell check',float(ell.subs({h:0.5,hp:0.4,V1:V1n,V2:V2n})))
# (5) numerical simulation
M,g=0.05,9.8; Phi0n,rn=1e-4,5e-3; Rn=2e-3
hn,ln,e2=0.5,0.2,0.8
dP=sp.lambdify(S,dPhi.subs({P0:Phi0n,r:rn}),'numpy')
def rhs(t,y,Rv):
    z,vz=y; sc=z-ln
    F=-(dP(sc)**2)*vz/Rv if Rv else 0.0
    return [vz,-g+F/M]
def run(Rv):
    ev=lambda t,y,Rv: y[0]; ev.terminal=True; ev.direction=-1
    sol=solve_ivp(rhs,[0,5],[hn,0],args=(Rv,),events=ev,rtol=1e-11,atol=1e-13,max_step=1e-4)
    vfl=sol.y_events[0][0][1]; vfl1=-np.sqrt(e2)*vfl
    ev2=lambda t,y,Rv: y[1]; ev2.terminal=True; ev2.direction=-1
    sol2=solve_ivp(rhs,[0,5],[0,vfl1],args=(Rv,),events=ev2,rtol=1e-11,atol=1e-13,max_step=1e-4)
    return sol2.y_events[0][0][0], sol.y_events
htop0=run(None)[0]; htop=run(Rn)[0]
print('open coil top',htop0,'(expect',e2*hn,')')
dh_num=htop0-htop
u1=np.sqrt(2*g*(hn-ln)); u2=np.sqrt(2*g*(e2*hn-ln))
V1v=Phi0n*u1/(2*rn); V2v=Phi0n*u2/(2*rn)
dh_formula=3*np.pi*Phi0n*(e2*V1v+V2v)/(16*M*g*Rn)
print('dh num',dh_num,'formula',dh_formula,'rel err',dh_num/dh_formula-1)
assert abs(dh_num/dh_formula-1)<0.02
# R を半分 → Δh 約2倍
dh2=htop0-run(Rn/2)[0]; print('ratio R/2:',dh2/dh_num)
print('OK')
